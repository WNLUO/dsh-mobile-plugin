'use strict';

/**
 * 「FRP 导入」的解析函数：从 frpc 配置里认出手机该拨的公网入口。
 *
 * 纯函数，直接加载 React 那份源码来跑（Node 能擦掉 TS 类型）。要钉的是「各种常见写法都能认出
 * 正确的那一栏」，而不是某一个服务商的私有格式。
 */

const assert = require('node:assert/strict');
const path = require('node:path');
const test = require('node:test');
const { pathToFileURL } = require('node:url');

const SRC = path.join(__dirname, '..', 'React', 'src', 'lib', 'frp-config.ts');

async function load() {
  return import(pathToFileURL(SRC).href);
}

test('直接填 host:port（含 http 前缀）→ 进 TCP 栏', async () => {
  const { parseFrpConfig } = await load();
  assert.deepEqual(parseFrpConfig('1.2.3.4:18787'), { ok: true, field: 'tcp', value: '1.2.3.4:18787', kind: 'tcp' });
  assert.deepEqual(parseFrpConfig('http://1.2.3.4:18787/'), { ok: true, field: 'tcp', value: '1.2.3.4:18787', kind: 'tcp' });
  assert.deepEqual(parseFrpConfig('[240e::1]:18787'), { ok: true, field: 'tcp', value: '[240e::1]:18787', kind: 'tcp' });
  assert.equal(parseFrpConfig('1.2.3.4:70000').reason, 'bad-tcp');
});

test('toml 的 tcp 转发（serverAddr + remotePort）→ TCP 栏', async () => {
  const { parseFrpConfig } = await load();
  const text = [
    'serverAddr = "203.0.113.5"',
    'serverPort = 7000',
    '',
    '[[proxies]]',
    'name = "dsh"',
    'type = "tcp"',
    'localIP = "127.0.0.1"',
    'localPort = 18787',
    'remotePort = 16000',
  ].join('\n');
  assert.deepEqual(parseFrpConfig(text), { ok: true, field: 'tcp', value: '203.0.113.5:16000', kind: 'tcp' });
});

test('老 ini 的 tcp 转发（下划线键）→ TCP 栏', async () => {
  const { parseFrpConfig } = await load();
  const text = ['[common]', 'server_addr = 203.0.113.5', 'server_port = 7000', '', '[ssh]', 'type = tcp', 'local_port = 22', 'remote_port = 6000'].join('\n');
  assert.deepEqual(parseFrpConfig(text), { ok: true, field: 'tcp', value: '203.0.113.5:6000', kind: 'tcp' });
});

test('https 转发（customDomains）→ 直连栏', async () => {
  const { parseFrpConfig } = await load();
  const text = ['serverAddr = "203.0.113.5"', '', '[[proxies]]', 'type = "https"', 'customDomains = ["dsh.example.com"]'].join('\n');
  assert.deepEqual(parseFrpConfig(text), { ok: true, field: 'direct', value: 'https://dsh.example.com', kind: 'https' });
});

test('ini 的 https（custom_domains 逗号分隔）→ 直连栏', async () => {
  const { parseFrpConfig } = await load();
  const text = ['[common]', 'server_addr = 203.0.113.5', '', '[web]', 'type = https', 'custom_domains = dsh.example.com, alt.example.com'].join('\n');
  assert.deepEqual(parseFrpConfig(text), { ok: true, field: 'direct', value: 'https://dsh.example.com', kind: 'https' });
});

test('空 / 认不出 → 明确的失败原因', async () => {
  const { parseFrpConfig } = await load();
  assert.equal(parseFrpConfig('').reason, 'empty');
  assert.equal(parseFrpConfig('   \n  ').reason, 'empty');
  assert.equal(parseFrpConfig('[common]\nserver_addr = 1.2.3.4\n').reason, 'no-address');
});

test('PassNAT 那种没有 remotePort 的 tcp：按本机端口推，并标明是推的', async () => {
  const { parseFrpConfig } = await load();
  const text = [
    '# Config generated by PassNAT.',
    'serverAddr = "103.40.14.14"',
    'serverPort = 8000',
    'metadatas.id = "4YGHAI7wM2"',
    'transport.heartbeatInterval = 120',
    '',
    '[[proxies]]',
    'name = "b1552436-9de8-4867-ae0c-1eea27e0b16c"',
    'type = "tcp"',
    'localIP = "127.0.0.1"',
    'localPort = 18787',
  ].join('\n');
  assert.deepEqual(parseFrpConfig(text), {
    ok: true,
    field: 'tcp',
    value: '103.40.14.14:18787',
    kind: 'tcp',
    note: 'inferred-local-port',
    port: 18787,
  });
});

test('有 remotePort 时以 remotePort 为准，不会错用 localPort', async () => {
  const { parseFrpConfig } = await load();
  const text = ['serverAddr = "1.2.3.4"', '[[proxies]]', 'type = "tcp"', 'localPort = 22', 'remotePort = 6000'].join('\n');
  assert.deepEqual(parseFrpConfig(text), { ok: true, field: 'tcp', value: '1.2.3.4:6000', kind: 'tcp' });
});

test('多条代理：优先选带 remotePort 的 tcp', async () => {
  const { parseFrpConfig } = await load();
  const text = [
    'serverAddr = "1.2.3.4"',
    '[[proxies]]',
    'type = "tcp"',
    'localPort = 22',
    '[[proxies]]',
    'type = "tcp"',
    'localPort = 8080',
    'remotePort = 16000',
  ].join('\n');
  assert.deepEqual(parseFrpConfig(text), { ok: true, field: 'tcp', value: '1.2.3.4:16000', kind: 'tcp' });
});

test('JSON 配置也认', async () => {
  const { parseFrpConfig } = await load();
  const text = JSON.stringify({ serverAddr: '1.2.3.4', proxies: [{ type: 'tcp', localPort: 18787, remotePort: 16000 }] });
  assert.deepEqual(parseFrpConfig(text), { ok: true, field: 'tcp', value: '1.2.3.4:16000', kind: 'tcp' });
});
